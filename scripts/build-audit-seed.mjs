/**
 * data/audit-criteria.json -> supabase/seed/audit_criteria.sql
 *
 * The criteria and targets live in one place, the city config file. This
 * writes the SQL that loads them into `criteria` and `typology_benchmarks`.
 * Re-running it after Anat's official list arrives replaces the placeholders
 * (upsert; flip "placeholder" to false in the JSON when a value is official).
 */
import fs from "node:fs";

const src = JSON.parse(fs.readFileSync("data/audit-criteria.json", "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? "null" : String(v));
const placeholder = src.placeholder === false ? "false" : "true";

const lines = [
  "-- Generated by scripts/build-audit-seed.mjs from data/audit-criteria.json. Do not edit by hand.",
  "begin;",
];
src.criteria.forEach((c, i) => {
  lines.push(
    `insert into public.criteria (id, family, name_he, metric, unit, method, vote_key, automation_level, measure, benchmark_key, source, placeholder, sort) values (${[
      q(c.id), q(c.family), q(c.name_he), q(c.metric), q(c.unit), q(c.method), q(c.vote_key),
      q(c.automation_level), q(c.measure), q(c.benchmark_key), q(c.source), placeholder, i + 1,
    ].join(", ")}) on conflict (id) do update set family = excluded.family, name_he = excluded.name_he, metric = excluded.metric, unit = excluded.unit, method = excluded.method, vote_key = excluded.vote_key, automation_level = excluded.automation_level, measure = excluded.measure, benchmark_key = excluded.benchmark_key, source = excluded.source, placeholder = excluded.placeholder, sort = excluded.sort;`,
  );
});
lines.push("delete from public.typology_benchmarks;");
for (const [typology, targets] of Object.entries(src.benchmarks)) {
  if (typology.startsWith("_")) continue;
  for (const c of src.criteria) {
    const range = c.benchmark_key ? targets[c.benchmark_key] : null;
    if (!range) continue;
    lines.push(
      `insert into public.typology_benchmarks (typology, criterion_id, target_min, target_max, placeholder) values (${q(typology)}, ${q(c.id)}, ${n(range[0])}, ${n(range[1])}, ${placeholder});`,
    );
  }
}
lines.push("commit;", "");
fs.writeFileSync("supabase/seed/audit_criteria.sql", lines.join("\n"));
console.log(`criteria: ${src.criteria.length}, file: supabase/seed/audit_criteria.sql`);
